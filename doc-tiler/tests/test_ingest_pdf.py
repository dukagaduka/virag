async def test_original_download_and_range(client, sample_pdf):
    doc_id = (await client.post("/tile", **pdf_form(sample_pdf))).json()["doc_id"]

    full = await client.get(f"/doc/{doc_id}")
    assert full.status_code == 200
    assert full.content == sample_pdf
    assert full.headers["accept-ranges"] == "bytes"
    assert doc_id in full.headers["content-disposition"]

    part = await client.get(f"/doc/{doc_id}", headers={"Range": "bytes=0-9"})
    assert part.status_code == 206
    assert part.content == sample_pdf[:10]
    assert part.headers["content-range"] == f"bytes 0-9/{len(sample_pdf)}"

    tail = await client.get(f"/doc/{doc_id}", headers={"Range": "bytes=-16"})
    assert tail.status_code == 206
    assert tail.content == sample_pdf[-16:]

    bad = await client.get(f"/doc/{doc_id}", headers={"Range": f"bytes={len(sample_pdf)}-"})
    assert bad.status_code == 416

    assert (await client.get("/doc/" + "0" * 64)).status_code == 404


async def test_delete_cascades(client, sample_pdf):
    doc_id = (await client.post("/tile", **pdf_form(sample_pdf))).json()["doc_id"]
    assert client.service.blobs.exists(doc_id)

    r = await client.delete(f"/doc/{doc_id}")
    assert r.status_code == 204
    assert not client.service.blobs.exists(doc_id)
    assert (await client.get("/get_tile", params={"doc_id": doc_id, "tile_num": 0})).status_code == 404
    assert await client.service.store.get_tiles(doc_id) == []


def _render_count(service, doc_type: str, path: str) -> float:
    from tiler import metrics

    return metrics.RENDERS.labels(doc_type=doc_type, path=path)._value.get()
